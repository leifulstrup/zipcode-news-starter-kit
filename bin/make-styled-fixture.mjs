// make-styled-fixture — regenerate fixtures/styled-issue.html.
//
//   node bin/make-styled-fixture.mjs
//
// The styled fixture is `good-issue.html` with its minimal stylesheet REPLACED
// by `house-style.css` — which is what an instance following the brief actually
// ships. It exists because for a long time the gates' own fixture and the file
// publishers inline were different files, so nothing exercised the gates against
// what readers actually get; three separate defects came out of that one gap.
//
// REPLACED, not prepended: the fixture keeps a deliberately minimal stylesheet
// so the gates can be tested cheaply, and those rules come later in the cascade.
// Prepending left them overriding the real sheet — the rank badge measured 21px
// against the house style's 26px — which would have made the fixture prove the
// wrong thing while looking right.
//
// Run this after editing either input; doctor asserts the result renders
// correctly, and bin/render-check.mjs is what actually looks at it.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/config.mjs';

const good = readFileSync(join(ROOT, 'fixtures', 'good-issue.html'), 'utf8');
const css = readFileSync(join(ROOT, 'fixtures', 'house-style.css'), 'utf8');

if (!/<style>[\s\S]*?<\/style>/.test(good)) {
  console.error('make-styled-fixture: good-issue.html has no <style> block to replace.');
  process.exit(1);
}

const banner = `<!-- GENERATED by bin/make-styled-fixture.mjs — do not edit by hand.
     good-issue.html with fixtures/house-style.css in place of its minimal
     stylesheet: what an instance following the brief actually ships. -->\n`;

const out = banner + good.replace(/<style>[\s\S]*?<\/style>/,
  `<style>\n/* ---- fixtures/house-style.css ---- */\n${css}\n</style>`);

writeFileSync(join(ROOT, 'fixtures', 'styled-issue.html'), out);
console.log(`wrote fixtures/styled-issue.html (${out.length} bytes, house-style.css ${css.length} bytes)`);
console.log('now run: node bin/render-check.mjs');
