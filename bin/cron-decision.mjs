#!/usr/bin/env node
/**
 * Should THIS scheduled trigger publish? — the daylight-saving and backstop decision.
 *
 *   node bin/cron-decision.mjs --cron "0 20 * * 5"
 *   node bin/cron-decision.mjs --cron "0 3 * * 6" --now 2026-11-14T03:00:00Z --issues-dir issues
 *
 * WHY THIS IS A SCRIPT
 * weekly.yml now carries three crons and only one of them should ever do the work. Which
 * one depends on the date, because GitHub cron is UTC and does not follow daylight saving.
 * Getting that wrong is not a small fault in either direction: no edition that week, or two
 * editions an hour apart. That is not a decision to leave as an `if:` expression nobody can
 * run — so it lives here, it is a pure function of (cron, clock, config, what is on disk),
 * and doctor drives it through both seasons and both hemispheres.
 *
 * THE THREE CRONS, all generated by bin/sync-crons.mjs from site.config.json:
 *   two publish crons — the two UTC hours that land on your local publish hour, one correct
 *                       in summer and one in winter. In a zone without daylight saving they
 *                       collapse to one and there is nothing to choose.
 *   one backstop      — hours later, and it does nothing unless the week is still
 *                       unpublished. GitHub silently DROPS scheduled runs during platform
 *                       degradation and never retries them; this is the only defence, and
 *                       on a normal week it costs a job that exits in seconds.
 */

import { readFileSync, existsSync, readdirSync } from 'fs';
import { appendFileSync } from 'fs';
import path from 'path';

const argv = process.argv.slice(2);
const arg = (n, d = null) => { const i = argv.indexOf(n); return i > -1 ? argv[i + 1] : d; };

const cronIn    = (arg('--cron') || '').trim();
const now       = arg('--now') ? new Date(arg('--now')) : new Date();
const issuesDir = arg('--issues-dir', 'issues');
const configPath = arg('--config', 'site.config.json');

const cfg = existsSync(configPath) ? JSON.parse(readFileSync(configPath, 'utf8')) : {};
const TZ = cfg.timezone || 'UTC';

function offsetHours(tz, date) {
  const p = Object.fromEntries(new Intl.DateTimeFormat('en-US', {
    timeZone: tz, hour12: false, year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
  }).formatToParts(date).map(x => [x.type, x.value]));
  const asIfUtc = Date.UTC(+p.year, +p.month - 1, +p.day, +p.hour % 24, +p.minute, +p.second);
  return Math.round((asIfUtc - date.getTime()) / 3600000);
}

const m = String(cfg.cronUtc || '').trim().match(/^(\d+)\s+(\d+)\s+\*\s+\*\s+([0-6])$/);
if (!m) {
  // Without a usable config this must not silently skip a publication.
  out(true, `site.config.json cronUtc is missing or malformed, so the schedule cannot be reasoned about. Proceeding rather than skipping — a missed edition is worse than an extra one, and the fault is in the config.`);
}
const [, , cfgHour, cfgDow] = m;
const D = Number(cfgDow);

/* The local hour the publisher means. Pinned by `publishLocalHour` if they set it; otherwise
   whatever cronUtc means today, which is what they are already getting. */
const localHour = cfg.publishLocalHour !== undefined
  ? Number(cfg.publishLocalHour)
  : (Number(cfgHour) + offsetHours(TZ, now) + 24) % 24;

/* Which UTC slots land on that local hour, in each half of the year. Identical in a zone
   that does not change its clocks. */
const yr = now.getUTCFullYear();
const slotFor = off => {
  const raw = localHour - off;
  return { h: ((raw % 24) + 24) % 24, d: (((D + Math.floor(raw / 24)) % 7) + 7) % 7 };
};
const slots = [
  slotFor(offsetHours(TZ, new Date(Date.UTC(yr, 0, 15, 12)))),
  slotFor(offsetHours(TZ, new Date(Date.UTC(yr, 6, 15, 12)))),
];
const isPublishSlot = c => {
  const p = c.match(/^(\d+)\s+(\d+)\s+\*\s+\*\s+([0-6])$/);
  return !!p && slots.some(s => s.h === Number(p[2]) && s.d === Number(p[3]));
};

/* The edition date this trigger is for. A publish cron means today (in the publication's own
   timezone, not UTC — at 00:00 UTC Saturday a Los Angeles paper is still on Friday). The
   backstop means the most recent publish weekday at or before now. */
const localDate = d => new Intl.DateTimeFormat('en-CA', { timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);
const localDow  = d => Number(new Intl.DateTimeFormat('en-US', { timeZone: TZ, weekday: 'short' }).format(d)
  .replace(/Sun/, 0).replace(/Mon/, 1).replace(/Tue/, 2).replace(/Wed/, 3)
  .replace(/Thu/, 4).replace(/Fri/, 5).replace(/Sat/, 6));

function lastPublishDay(from) {
  const d = new Date(from);
  for (let i = 0; i < 8; i++) {
    if (localDow(d) === D) return localDate(d);
    d.setUTCDate(d.getUTCDate() - 1);
  }
  return localDate(from);
}

function out(proceed, reason, week) {
  const w = week || localDate(now);
  console.log(JSON.stringify({ proceed, reason, week: w, localHour, timezone: TZ }, null, 2));
  if (process.env.GITHUB_OUTPUT) {
    appendFileSync(process.env.GITHUB_OUTPUT, `proceed=${proceed}\nweek=${w}\nreason=${reason}\n`);
  }
  process.exit(0);
}

/* Manual dispatch: no cron, no schedule reasoning. The publisher asked. */
if (!cronIn) out(true, 'Manual dispatch — no schedule checks apply.', localDate(now));

if (isPublishSlot(cronIn)) {
  const h = Number(now.toISOString().slice(11, 13));
  const localNow = (h + offsetHours(TZ, now) + 24) % 24;
  if (localNow !== localHour) {
    out(false,
      `This cron fired at ${String(localNow).padStart(2, '0')}:00 in ${TZ}, and this publication goes out at ` +
      `${String(localHour).padStart(2, '0')}:00. The other publish cron is today's — daylight saving decides which, ` +
      `and both are scheduled so that one of them is always right. This is the guard working, not a fault.`,
      localDate(now));
  }
  out(true, `This is the ${String(localHour).padStart(2, '0')}:00 ${TZ} trigger today.`, localDate(now));
}

/* Anything else generated into this file is the backstop. */
const week = lastPublishDay(now);
const issueFile = path.join(issuesDir, `${week}.html`);
if (existsSync(issueFile)) {
  out(false, `Backstop: ${issueFile} already exists, so the scheduled run published normally. Nothing to do.`, week);
}
out(true,
  `Backstop firing: no issue exists for ${week}, so the scheduled run did not publish. GitHub drops ` +
  `scheduled runs during platform degradation and never retries them, which is the case this exists for. ` +
  `Writing the edition now.`,
  week);
